-- PostgreSQL convierte Tarea sin comillas a tarea; por eso el cliente usa
-- public.tarea como nombre de tabla.
create table if not exists public.tarea (
  id bigint generated by default as identity primary key,
  titulo varchar not null,
  descripcion varchar not null default '',
  estado text not null default 'Pendiente'
    check (estado in ('Pendiente', 'En progreso', 'Completada')),
  responsible_id uuid not null references auth.users(id) on delete cascade,
  created_by uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

-- Para una tabla ya creada con id, titulo, descripcion y estado.
alter table public.tarea
  add column if not exists responsible_id uuid references auth.users(id) on delete cascade,
  add column if not exists created_by uuid references auth.users(id) on delete cascade,
  add column if not exists created_at timestamptz not null default now();

create index if not exists tarea_responsible_created_at_idx
  on public.tarea (responsible_id, created_at desc);

alter table public.tarea enable row level security;
revoke all on table public.tarea from anon;
grant select, insert, update, delete on table public.tarea to authenticated;

drop policy if exists "Enable read access for all users" on public.tarea;
drop policy if exists "Users read their Tarea" on public.tarea;
drop policy if exists "Users create their Tarea" on public.tarea;
drop policy if exists "Users update their Tarea" on public.tarea;
drop policy if exists "Users delete their Tarea" on public.tarea;

create policy "Users read their Tarea"
  on public.tarea for select to authenticated
  using (auth.uid() = responsible_id or auth.uid() = created_by);

create policy "Users create their Tarea"
  on public.tarea for insert to authenticated
  with check (auth.uid() = responsible_id and auth.uid() = created_by);

create policy "Users update their Tarea"
  on public.tarea for update to authenticated
  using (auth.uid() = responsible_id or auth.uid() = created_by)
  with check (auth.uid() = responsible_id or auth.uid() = created_by);

create policy "Users delete their Tarea"
  on public.tarea for delete to authenticated
  using (auth.uid() = responsible_id or auth.uid() = created_by);
